function getDepartmentIconPath($departmentId)
{
    $departmentIcons = getDepartmentIconMap();

    return $departmentIcons[(string) $departmentId] ?? '/img/otdeleniya.svg';
}

function getDepartmentItemById($departmentId)
{
    foreach (getDepartmentItems() as $departmentItem) {
        if ($departmentItem['id'] === $departmentId) {
            return $departmentItem;
        }
    }

    return null;
}
